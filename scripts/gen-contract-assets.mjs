// Embeds the fonts and logo the contract PDF needs as base64, so the PDF engine never depends on files being present on the server.
// Run after changing the logo or fonts:  node scripts/gen-contract-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";

const font = (name) => readFileSync(`node_modules/@fontsource/tajawal/files/tajawal-${name}-normal.woff2`).toString("base64");
const out = `// Generated by scripts/gen-contract-assets.mjs -- do not edit by hand.
export const CONTRACT_FONTS = {
  arabic400: "${font("arabic-400")}",
  arabic700: "${font("arabic-700")}",
  latin400: "${font("latin-400")}",
  latin700: "${font("latin-700")}",
};
export const CONTRACT_LOGO_JPEG = "${readFileSync("public/osta-logo.jpg").toString("base64")}";
`;
writeFileSync("src/lib/contracts/assets.generated.ts", out);
console.log("assets.generated.ts", out.length, "bytes");
