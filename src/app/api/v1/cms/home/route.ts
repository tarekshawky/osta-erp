import { prisma } from "@/lib/prisma";
import { apiSuccess, apiError, corsPreflight } from "@/lib/apiResponse";
import { promoteDueScheduledPages } from "@/lib/cms/publish";
import { toPublicPage } from "@/lib/cms/publicPage";

export function OPTIONS() {
  return corsPreflight();
}

// The published, editable homepage. Until the owner publishes it (or after they unpublish it) this answers
// 200 { notFound: true }, which tells the site to use its built-in homepage.
//
// It is deliberately NOT an HTTP 404: Next.js refuses to cache non-2xx fetches and keeps serving the last good
// copy when a refresh "fails", so a 404 would leave an unpublished page online indefinitely.
export async function GET() {
  await promoteDueScheduledPages();
  const page = await prisma.cmsPage.findFirst({ where: { isHomepage: true, status: "PUBLISHED", deletedAt: null }, include: { publishedVersion: true } });
  if (!page?.publishedVersion) return apiSuccess({ notFound: true });
  // No per-page structured data here: the homepage's business data is generated by the site itself.
  const publicPage = toPublicPage(page, page.publishedVersion);
  if (!publicPage) return apiError("invalid_content", "The homepage content is invalid.", 422);
  return apiSuccess({ ...publicPage, slug: "" });
}
